import {afterAll,beforeAll,expect,it} from 'vitest';
import {PGlite} from '@electric-sql/pglite';
import {readFile,readdir} from 'node:fs/promises';
let db:PGlite;
let source:string;
beforeAll(async()=>{
 db=new PGlite();
 await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
 create schema auth;create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth to anon,authenticated,service_role;grant execute on function auth.uid() to anon,authenticated,service_role;
 create schema storage;create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,owner_id text);
 alter table storage.objects enable row level security;grant usage on schema storage to anon,authenticated,service_role;grant all on storage.objects to anon,authenticated,service_role;
 insert into auth.users values('70000000-0000-4000-8000-000000000001');`);
 const dir=new URL('../../supabase/migrations/',import.meta.url);
 for(const name of (await readdir(dir)).filter(f=>f.endsWith('.sql')&&f<'20261005035035').sort())await db.exec(await readFile(new URL(name,dir),'utf8'));
 source=await readFile(new URL('20261005035035_fortius_inmuebles_identity.sql',dir),'utf8');
 await db.exec(`insert into public.mnt_staff(user_id,role) values('70000000-0000-4000-8000-000000000001','admin');
 insert into public.mnt_records(collection,id,data,version) values('notas','preserved','{"texto":"Conservar sin editar"}',7);`);
 for(let revision=1;revision<7;revision++)await db.exec("update public.mnt_records set data=data where id='preserved'");
});
afterAll(async()=>{await db?.close();});
it('rechaza Storage no verificado y revierte atómicamente',async()=>{
 await db.exec(`insert into storage.objects(bucket_id,name) values('mnt-private','protected.pdf');`);
 await expect(db.exec(source)).rejects.toThrow(/Storage must be copied/);
 await db.exec('rollback');
 expect((await db.query(`select version from public.mnt_records where id='preserved'`)).rows).toEqual([{version:7}]);
 await db.exec(`delete from storage.objects where name='protected.pdf';`);
});
it('conserva filas, revisiones, OIDs, RLS, ACL y permisos del esquema completo',async()=>{
 const tableSnapshot=(prefix:string)=>`select oid,relrowsecurity,relacl::text from pg_class where relnamespace='public'::regnamespace and relkind='r' and starts_with(relname,'${prefix}') order by oid`;
 const functionSnapshot=(prefix:string)=>`select oid,proacl::text,prosecdef,proconfig from pg_proc where pronamespace='public'::regnamespace and starts_with(proname,'${prefix}') order by oid`;
 const tables=(await db.query(tableSnapshot('mnt_'))).rows;
 const functions=(await db.query(functionSnapshot('mnt_'))).rows;
 const records=(await db.query('select * from public.mnt_records order by collection,id')).rows;
 const revisions=(await db.query('select * from public.mnt_record_revisions order by collection,id')).rows;
 await db.exec(source);
 expect((await db.query(tableSnapshot('fortius_inmuebles_'))).rows).toEqual(tables);
 expect((await db.query(functionSnapshot('fortius_inmuebles_'))).rows).toEqual(functions);
 expect((await db.query('select * from public.fortius_inmuebles_records order by collection,id')).rows).toEqual(records);
 expect((await db.query('select * from public.fortius_inmuebles_record_revisions order by collection,id')).rows).toEqual(revisions);
 await db.exec('set role anon');
 await expect(db.query('select * from public.fortius_inmuebles_records')).rejects.toMatchObject({code:'42501'});
 expect((await db.query("select * from public.mnt_public_records('notas')")).rows).toEqual([]);
 await expect(db.query("select public.fortius_inmuebles_public_url('/fortius-inmuebles-private/private.pdf')")).rejects.toMatchObject({code:'42501'});
 await db.exec('reset role');
 expect((await db.query("select public.fortius_inmuebles_public_url('/fortius-inmuebles-private/private.pdf') as safe")).rows).toEqual([{safe:false}]);
 await expect(db.exec(source)).rejects.toThrow(/source records table is missing/);await db.exec('rollback');
 await db.exec(await readFile(new URL('../../supabase/migrations/20261005040239_fortius_inmuebles_retire_compatibility.sql',import.meta.url),'utf8'));
 expect((await db.query("select to_regprocedure('public.mnt_public_records(text)') as reader")).rows).toEqual([{reader:null}]);
});
