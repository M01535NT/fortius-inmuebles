-- PN-02 · Bloque 6: historial con actor y notas internas que no se editan (solo se corrigen con otra nota).
-- No sustituye a record_history ni a expediente_actividad, que siguen sirviendo al panel viejo.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
select pg_advisory_xact_lock(781023);

create table public.fortius_inmuebles_historial (
  id bigint generated by default as identity primary key,  -- «by default»: la restauración vuelve a poner los mismos números
  entidad text not null check (entidad in ('asunto', 'persona', 'inmueble', 'pendiente', 'movimiento', 'consulta', 'archivo', 'formato')),
  entidad_id text not null,
  asunto_id uuid references public.fortius_inmuebles_expedientes (id) on delete restrict,
  accion text not null check (accion ~ '^[a-z_]{2,40}$'),
  resumen text not null check (length(btrim(resumen)) between 1 and 500),
  detalle jsonb,
  actor_id uuid,
  actor_tipo text not null default 'usuario' check (actor_tipo in ('usuario', 'sistema', 'publico')),
  check (actor_tipo <> 'usuario' or actor_id is not null),
  created_at timestamptz not null default clock_timestamp()
);
create index on public.fortius_inmuebles_historial (entidad, entidad_id, created_at desc);
create index on public.fortius_inmuebles_historial (asunto_id, created_at desc) where asunto_id is not null;
alter table public.fortius_inmuebles_historial enable row level security;
revoke all on public.fortius_inmuebles_historial from anon, authenticated;
grant select on public.fortius_inmuebles_historial to authenticated;
grant all on public.fortius_inmuebles_historial to service_role;
create policy historial_read on public.fortius_inmuebles_historial for select to authenticated using (
  (select public.fortius_inmuebles_is_admin())
  or (asunto_id is not null and public.fortius_inmuebles_puede_ver_asunto(asunto_id))
  or (public.fortius_inmuebles_is_staff() and actor_id = (select auth.uid())));
create trigger fortius_solo_agregar before update or delete on public.fortius_inmuebles_historial
  for each row execute function public.fortius_inmuebles_solo_agregar();

-- Única forma de escribir el historial desde la app: el actor es siempre quien está en sesión.
create function public.fortius_inmuebles_anotar_historial(p_entidad text, p_entidad_id text, p_asunto uuid, p_accion text, p_resumen text, p_detalle jsonb default null)
returns bigint language plpgsql security definer set search_path = '' as $$
declare nuevo bigint;
begin
  if not public.fortius_inmuebles_is_staff() then
    raise sqlstate 'PT403' using message = 'Sin acceso';
  end if;
  if p_asunto is not null and not public.fortius_inmuebles_puede_ver_asunto(p_asunto) then
    raise sqlstate 'PT403' using message = 'Sin acceso a ese asunto';
  end if;
  insert into public.fortius_inmuebles_historial (entidad, entidad_id, asunto_id, accion, resumen, detalle, actor_id, actor_tipo)
  values (p_entidad, p_entidad_id, p_asunto, p_accion, p_resumen, p_detalle, auth.uid(), 'usuario')
  returning id into nuevo;
  return nuevo;
end; $$;
revoke all on function public.fortius_inmuebles_anotar_historial(text, text, uuid, text, text, jsonb) from public, anon;
grant execute on function public.fortius_inmuebles_anotar_historial(text, text, uuid, text, text, jsonb) to authenticated, service_role;

create table public.fortius_inmuebles_notas_internas (
  id uuid primary key default gen_random_uuid(),
  asunto_id uuid references public.fortius_inmuebles_expedientes (id) on delete restrict,
  persona_id text,
  persona_collection text not null default 'clientes' check (persona_collection = 'clientes'),
  inmueble_id text,
  inmueble_collection text not null default 'propiedades' check (inmueble_collection = 'propiedades'),
  check (num_nonnulls(asunto_id, persona_id, inmueble_id) = 1),
  texto text not null check (length(btrim(texto)) between 1 and 5000),
  corrige_a uuid references public.fortius_inmuebles_notas_internas (id),
  autor uuid not null default auth.uid() references auth.users (id),
  created_at timestamptz not null default clock_timestamp(),
  foreign key (persona_collection, persona_id) references public.fortius_inmuebles_records (collection, id) on delete restrict,
  foreign key (inmueble_collection, inmueble_id) references public.fortius_inmuebles_records (collection, id) on delete restrict
);
create index on public.fortius_inmuebles_notas_internas (asunto_id, created_at desc) where asunto_id is not null;
create index on public.fortius_inmuebles_notas_internas (persona_id, created_at desc) where persona_id is not null;
create index on public.fortius_inmuebles_notas_internas (inmueble_id, created_at desc) where inmueble_id is not null;
alter table public.fortius_inmuebles_notas_internas enable row level security;
revoke all on public.fortius_inmuebles_notas_internas from anon, authenticated;
grant select, insert on public.fortius_inmuebles_notas_internas to authenticated;
grant all on public.fortius_inmuebles_notas_internas to service_role;
-- Quién ve una nota: director; en un asunto, quien ve el asunto; en una persona, quien la lleva; en un inmueble, el equipo.
create policy notas_read on public.fortius_inmuebles_notas_internas for select to authenticated using (
  (select public.fortius_inmuebles_is_admin())
  or (asunto_id is not null and public.fortius_inmuebles_puede_ver_asunto(asunto_id))
  or (persona_id is not null and public.fortius_inmuebles_is_staff() and public.fortius_inmuebles_can_access_client_id(persona_id))
  or (inmueble_id is not null and public.fortius_inmuebles_is_staff()));
create policy notas_insert on public.fortius_inmuebles_notas_internas for insert to authenticated
  with check (autor = (select auth.uid()) and (
    (select public.fortius_inmuebles_is_admin())
    or (asunto_id is not null and public.fortius_inmuebles_puede_ver_asunto(asunto_id))
    or (persona_id is not null and public.fortius_inmuebles_is_staff() and public.fortius_inmuebles_can_access_client_id(persona_id))
    or (inmueble_id is not null and public.fortius_inmuebles_is_staff())));
create trigger fortius_solo_agregar before update or delete on public.fortius_inmuebles_notas_internas
  for each row execute function public.fortius_inmuebles_solo_agregar();

commit;
